#!/usr/bin/env python3
"""Generate native Pelican v3 and compatible v2 eggs from the audited install script."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = 'https://raw.githubusercontent.com/Cerberus-Labs-Technologies/Cerberus-TS-Framework/main/'
IMAGE = 'ghcr.io/cerberus-labs-technologies/cerberus-ts-framework:latest'


def variable(name, env, default, rules, description, editable=True):
    return dict(name=name, description=description, env_variable=env, default_value=default,
                user_viewable=True, user_editable=editable, rules=rules)


def eggs():
    variables = [
        variable('TeamSpeak host', 'CERBERUS_HOST', '', 'required|string|max:253', 'Host/IP des TeamSpeak-Servers; kein localhost für einen anderen Container.'),
        variable('Query transport', 'CERBERUS_TRANSPORT', 'SSH', 'required|in:SSH,HTTPS,HTTP,RAW', 'TS6: SSH oder WebQuery. RAW nur mit TS3.'),
        variable('TeamSpeak generation', 'CERBERUS_GENERATION', 'TS6', 'required|in:TS6,TS3', 'Servergeneration.'),
        variable('Query port', 'CERBERUS_PORT', '24873', 'required|integer|between:1,65535', 'Ausgehender Query-Port des TeamSpeak-Servers; keine Bot-Allocation.'),
        variable('Query username', 'CERBERUS_USERNAME', 'serveradmin', 'required|string|max:100', 'SSH-/RAW-Query-Benutzer.'),
        variable('Query password', 'CERBERUS_PASSWORD', '', 'nullable|string|max:1024', 'Nur als Umgebung übergeben; leer lassen für Passwort/SSH-Key in config/cerberus.properties. Panel-Benutzer mit Variablenrechten können diesen Wert lesen.'),
        variable('WebQuery API key', 'CERBERUS_API_KEY', '', 'nullable|string|max:1024', 'Nur für HTTP/HTTPS; alternativ in der geschützten Konfigurationsdatei.'),
        variable('Virtual server ID', 'CERBERUS_SERVER_ID', '1', 'required|integer|min:1', 'TeamSpeak Virtual-Server-ID; Voice-Port wird vom Server ermittelt.'),
        variable('Query nickname', 'CERBERUS_NICKNAME', 'Cerberus TS', 'required|string|between:3,30', 'Für jede Framework-Instanz einen eigenen Namen verwenden.'),
        variable('Administrator UID', 'CERBERUS_ADMIN_UID', '', 'nullable|string|max:100', 'Stabile TeamSpeak-UID für Framework-Adminrechte; kein Nickname.'),
        variable('Voice server password', 'CERBERUS_VOICE_PASSWORD', '', 'nullable|string|max:1024', 'Optionales Voice-Passwort; unabhängig vom Query-Passwort.'),
        variable('Bundled plugins', 'CERBERUS_BUNDLED_PLUGINS', 'welcome,music', 'required|string|max:100', 'Kommagetrennt: welcome,music,server-setup oder none. server-setup ändert den TS-Server beim Start und ist standardmäßig aus.'),
        variable('Video public IPv4', 'CERBERUS_VIDEO_PUBLIC_ADDRESS', '', 'nullable|ipv4', 'Für Video-Bots: öffentliche IPv4 des Pelican-Nodes. Zusätzliche UDP-Allocations müssen 1:1 veröffentlicht werden; siehe docs/video.md.'),
        variable('Video UDP first port', 'CERBERUS_VIDEO_PORT_MIN', '24900', 'required|integer|between:1024,65534', 'Erster UDP-Port für WebRTC. Alle Ports bis einschließlich Video UDP last port als zusätzliche Allocations zuweisen und in der Firewall freigeben.'),
        variable('Video UDP last port', 'CERBERUS_VIDEO_PORT_MAX', '24919', 'required|integer|between:1025,65535', 'Letzter UDP-Port für WebRTC; muss größer als der erste Port sein. Primäre TCP-Allocation bleibt das Webinterface.'),
        variable('YouTube cookies file', 'CERBERUS_MUSIC_COOKIES_FILE', '', 'nullable|string|max:1024', 'Optionaler Pfad zur privaten Netscape-Cookie-Datei, z. B. /home/container/config/youtube.cookies.txt. Nur den Pfad eintragen, niemals Cookie-Inhalte. Gilt für Audio und Video.'),
        variable('Maximum music bots', 'CERBERUS_MUSIC_MAX_BOTS', '4', 'required|integer|between:1,32', 'Jeder Musikbot belegt einen TeamSpeak-Client-Slot.'),
        variable('Maximum queue size', 'CERBERUS_MUSIC_MAX_QUEUE', '100', 'required|integer|between:1,10000', 'Maximale Einträge je Musikbot.'),
    ]
    egg = dict(_comment='Generated by deploy/pelican/generate.py — Cerberus Labs',
               meta=dict(version='PLCN_v3', update_url=None),
               exported_at='2026-11-27T00:00:00+00:00', uuid='0b29601d-f4c0-4fae-9641-88fd71b6fc57',
               name='Cerberus TS', author='Cerberus Labs',
               description='Kotlin TeamSpeak framework with Paper-style plugins, extensible web interface and music bots. Requires the Cerberus runtime image, a verified SSH host key and one TCP allocation. Optional video bots need additional UDP allocations; see docs/video.md and docs/pelican.md.',
               tags=['TeamSpeak', 'Bots', 'Java', 'Cerberus Labs'], features=[],
               docker_images={'Cerberus TS · Java 21 + Music': IMAGE}, file_denylist=[],
               startup_commands={'Standard': 'bash /opt/cerberus/start.sh'},
               config=dict(files='{}', startup=json.dumps({'done': '[cerberus] CONNECTED'}), logs='{}', stop='stop'),
               scripts={'installation': dict(script=(ROOT/'install.sh').read_text(), container='debian:bookworm-slim', entrypoint='bash')},
               variables=variables)
    compatible = json.loads(json.dumps(egg))
    compatible['meta'] = dict(version='PTDL_v2', update_url=None)
    compatible['startup'] = compatible.pop('startup_commands')['Standard']
    for var in compatible['variables']:
        var['field_type'] = 'text'
    return {'egg-cerberus-ts.json': egg, 'egg-cerberus-ts-v2.json': compatible}


if __name__ == '__main__':
    for name, egg in eggs().items():
        (ROOT/name).write_text(json.dumps(egg, ensure_ascii=False, indent=4)+'\n')
